import assert from 'node:assert/strict';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const files = readdirSync('editions').filter(file => file.endsWith('.json')).sort();
assert(files.length, 'Add at least one edition.');
const history = new Map();
let current;
let legacy = {};

function checkedUrl(value) {
  const url = new URL(value);
  assert.equal(url.protocol, 'https:', value);
  assert(!url.username && !url.password, value);
}

for (const file of files) {
  const edition = JSON.parse(readFileSync('editions/' + file));
  assert.equal(edition.META.editionId + '.json', file);
  assert.match(file, /^\d{4}-\d{2}-\d{2}\.json$/);
  assert(edition.STORIES.length, file + ' has no stories');
  const ids = new Set();
  for (const story of edition.STORIES) {
    assert.match(story.id, /^[a-z0-9]+(?:-[a-z0-9]+)+$/);
    assert(!ids.has(story.id), 'Duplicate story ID ' + story.id);
    ids.add(story.id);
    assert(edition.TOPICS.some(topic => topic.id === story.topic), story.id);
    if (story.location) {
      const { label, lat, lng } = story.location;
      assert.equal(story.topic, 'world', 'Map location requires a World story: ' + story.id);
      assert(typeof label === 'string' && label.trim(), 'Missing map label: ' + story.id);
      assert(Number.isFinite(lat) && Math.abs(lat) <= 85, 'Invalid latitude: ' + story.id);
      assert(Number.isFinite(lng) && Math.abs(lng) <= 180, 'Invalid longitude: ' + story.id);
    }
    if (story.image) {
      assert.match(story.image, /^assets\/images\/[a-z0-9._-]+$/i, 'Invalid image path: ' + story.id);
      assert(existsSync(story.image), 'Missing image file: ' + story.image);
      assert(typeof story.imageAlt === 'string' && story.imageAlt.trim(), 'Missing imageAlt: ' + story.id);
    }
    checkedUrl(story.url);
    const coverage = edition.COVERAGE[story.id];
    assert(coverage?.length, 'Missing coverage: ' + story.id);
    const sources = new Set();
    for (const [name, date, url] of coverage) {
      assert(name && date && !sources.has(name), 'Invalid or duplicate outlet: ' + story.id);
      checkedUrl(url);
      sources.add(name);
    }
    assert(coverage.some(([, , url]) => url === story.url), 'Missing original article: ' + story.id);
    for (const group of story.comparison || []) {
      assert(group.label && group.points.length, story.id);
      for (const point of group.points) {
        assert(point.text && point.sources.length && point.sources.every(name => sources.has(name)), story.id);
      }
    }
    history.set(story.id, { ...story, coverage });
  }
  legacy = { ...legacy, ...edition.LEGACY_IDS };
  current = edition;
}

const currentIds = new Set(current.STORIES.map(story => story.id));
const archive = [...history.values()].filter(story => !currentIds.has(story.id));
const output = '/* Generated by scripts/build-editions.mjs. */\n' +
  'window.DAYBREAK = ' + JSON.stringify({ ...current, LEGACY_IDS: legacy }, null, 1) + ';\n' +
  'window.DAYBREAK_ARCHIVE = ' + JSON.stringify(archive) + ';\n';
if (process.argv.includes('--check')) {
  assert.equal(readFileSync('assets/data.js', 'utf8'), output, 'Regenerate assets/data.js before publishing.');
} else {
  writeFileSync('assets/data.js', output);
}
console.log(`Validated ${files.length} edition(s), ${currentIds.size} current stories and ${archive.length} archived stories.`);
